/**
 * @brief All data decoded from or destined for the CC207S bus.
 *
 * Field-to-byte mapping (0xDD telemetry frame, packet.data[N]):
 *   d1  water temperature        -> current_temperature  (raw/2 = degC)
 *   d2  discharge temperature    -> t_discharge
 *   d3  defrost temperature      -> t_defrost
 *   d4  suction temperature      -> t_suction   (physically wired to SEN5)
 *   d5  ambient air temperature  -> t_ambient   (physically wired to SEN4)
 *   d7  blocking faults          -> fault_codes + raw_faults_blocking
 *   d9  non-blocking sensor faults -> fault_codes + raw_faults_sensor
 *   d10 relay bitfield           -> action + the individual relay flags
 *   d11 PORT1 input              -> port1_open
 *
 * 0xD2/0xCC configuration frame (identical payload, different type byte):
 *   d2  setpoint                 -> target_temperature (raw/2 = degC)
 *   d7 bit 0x40  power state     -> mode (HEAT/OFF)
 *
 * See docs/CC207S-protocole.md for the full byte map, the E1-E4/P1-P5 fault
 * tables, and the test methodology behind each mapping.
 */
struct heat_pump_data_t {
    // ---- climate-facing state ---------------------------------------------
    optional<float> current_temperature;      ///< water temp, degC (d1)
    optional<float> target_temperature;       ///< setpoint, degC (config d2)
    optional<climate::ClimateMode> mode;      ///< HEAT or OFF, config d7 bit 0x40
    optional<climate::ClimateAction> action;  ///< derived from d10

    // ---- additional temperature sensors ------------------------------------
    optional<float> t_discharge;  ///< d2, degC
    optional<float> t_defrost;    ///< d3, degC
    optional<float> t_suction;    ///< d4, degC (physically SEN5)
    optional<float> t_ambient;    ///< d5, degC (physically SEN4)

    /// @brief Space-separated active codes, e.g. "E1", "P4 P5", or empty.
    std::string fault_codes;

    // ---- relay state (d10) -------------------------------------------------
    optional<uint8_t> raw_relays;
    optional<bool> compressor_on;        ///< d10 bit 0x02
    optional<bool> fan_on;               ///< d10 bit 0x10
    optional<bool> pump_on;              ///< d10 bit 0x08 (unwired on this unit)
    optional<bool> crankcase_heater_on;  ///< d10 bit 0x01 (unwired on this unit)

    // ---- other raw diagnostic fields ---------------------------------------
    optional<bool> port1_open;             ///< d11 bit 0x02
    optional<uint8_t> raw_faults_blocking; ///< d7
    optional<uint8_t> raw_faults_sensor;   ///< d9

    /// @brief True if a bit outside the mapped set was seen in d7/d9/d10 --
    /// flags functions this decode never observed (Heat/Cool 4-way valve,
    /// 2nd fan speed) instead of silently dropping them.
    optional<bool> unknown_bits_detected;

    /// @brief True if the compressor relay has been on a while without
    /// discharge-suction divergence: likely running without real compression
    /// (failed start capacitor, seized motor, lost charge). No protocol fault
    /// code covers this -- see cc207s_frame_telemetry.cpp.
    optional<bool> compressor_not_compressing;

    // ---- bus-layer bookkeeping (written directly by Bus.cpp/base_frame.cpp) --
    optional<uint32_t> last_heater_frame;
    optional<uint32_t> last_controller_frame;

    // ---- climate trait helpers ---------------------------------------------
    float get_min_target() const { return 15.0f; }
    float get_max_target() const { return 33.0f; }
    bool is_temperature_valid(float t) const {
        return t >= get_min_target() && t <= get_max_target();
    }
};

